/** The same quote for everyone on a given day (shift moves to the next one). */
export function quoteOfDay(shift = 0): QuoteItem {
  const dayIdx = Math.floor(Date.now() / 86_400_000);
  // Step through the list with a stride so consecutive days mix the kinds.
  return QUOTES[((dayIdx + shift) * 37) % QUOTES.length];
}
